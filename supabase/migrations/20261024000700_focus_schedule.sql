-- ==================== CALENDAR CONNECTIONS ====================

CREATE TABLE IF NOT EXISTS public.calendar_connections (
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  provider TEXT NOT NULL DEFAULT 'google' CHECK (provider IN ('google')),
  access_token_enc TEXT NOT NULL,
  refresh_token_enc TEXT,
  expires_at TIMESTAMPTZ,
  scope TEXT CHECK (scope IS NULL OR char_length(scope) <= 2000),
  email TEXT CHECK (email IS NULL OR char_length(email) <= 320),
  app_calendar_id TEXT CHECK (app_calendar_id IS NULL OR char_length(app_calendar_id) <= 1024),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_id, provider)
);

COMMENT ON COLUMN public.calendar_connections.access_token_enc IS 'Encrypted with lib/encryption.ts; service role only';
COMMENT ON COLUMN public.calendar_connections.refresh_token_enc IS 'Encrypted with lib/encryption.ts; service role only';
COMMENT ON COLUMN public.calendar_connections.app_calendar_id IS 'The secondary "NextMilestone" calendar our blocks are written to';

ALTER TABLE public.calendar_connections ENABLE ROW LEVEL SECURITY;

-- Users can see their own connection's non-secret columns (column grant below).
-- All writes go through the service role in the app's API routes.
DROP POLICY IF EXISTS calendar_connections_select_own ON public.calendar_connections;
CREATE POLICY calendar_connections_select_own ON public.calendar_connections
  FOR SELECT TO authenticated
  USING (auth.uid() = user_id);

REVOKE ALL ON public.calendar_connections FROM PUBLIC, anon, authenticated;
GRANT SELECT (user_id, provider, expires_at, scope, email, created_at, updated_at)
  ON public.calendar_connections TO authenticated;
GRANT ALL ON public.calendar_connections TO service_role;
