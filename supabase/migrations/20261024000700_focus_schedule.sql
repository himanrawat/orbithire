-- PRD v2, area 5: focus and schedule.
--
-- 1. focus_sessions: one row per finished focus timer (25, 50 or 90 minutes). The timer
--    runs offline in the browser and queues finished sessions; client_id makes the batch
--    sync (POST /api/focus/sessions) idempotent.
-- 2. schedule_blocks: the week's blocks by type. google_event_id links a block the user
--    created to the event we pushed to their Google Calendar.
-- 3. calendar_connections: OAuth tokens for Google Calendar, encrypted by the app
--    (lib/encryption.ts). Only the service role can read or write the token columns;
--    signed-in users can see whether they are connected, never the tokens.

-- ==================== FOCUS SESSIONS ====================

CREATE TABLE IF NOT EXISTS public.focus_sessions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  client_id UUID NOT NULL UNIQUE,
  task_label TEXT NOT NULL CHECK (char_length(task_label) BETWEEN 1 AND 200),
  task_ref TEXT CHECK (task_ref IS NULL OR char_length(task_ref) <= 200),
  planned_minutes SMALLINT NOT NULL CHECK (planned_minutes IN (25, 50, 90)),
  focused_seconds INTEGER CHECK (focused_seconds IS NULL OR focused_seconds BETWEEN 0 AND 5400),
  started_at TIMESTAMPTZ NOT NULL,
  ended_at TIMESTAMPTZ NOT NULL,
  completed BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT focus_sessions_time_order CHECK (ended_at >= started_at)
);

CREATE INDEX IF NOT EXISTS idx_focus_sessions_user_started
  ON public.focus_sessions(user_id, started_at DESC);

COMMENT ON COLUMN public.focus_sessions.client_id IS 'Generated by the browser; makes the offline sync idempotent';
COMMENT ON COLUMN public.focus_sessions.task_ref IS 'Optional daily plan item id the session was started from';
COMMENT ON COLUMN public.focus_sessions.focused_seconds IS 'Time the timer actually ran, pauses excluded';

ALTER TABLE public.focus_sessions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS focus_sessions_select_own ON public.focus_sessions;
CREATE POLICY focus_sessions_select_own ON public.focus_sessions
  FOR SELECT TO authenticated
  USING (auth.uid() = user_id);

DROP POLICY IF EXISTS focus_sessions_insert_own ON public.focus_sessions;
CREATE POLICY focus_sessions_insert_own ON public.focus_sessions
  FOR INSERT TO authenticated
  WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS focus_sessions_delete_own ON public.focus_sessions;
CREATE POLICY focus_sessions_delete_own ON public.focus_sessions
  FOR DELETE TO authenticated
  USING (auth.uid() = user_id);

REVOKE ALL ON public.focus_sessions FROM anon;
GRANT SELECT, INSERT, DELETE ON public.focus_sessions TO authenticated;
GRANT ALL ON public.focus_sessions TO service_role;

-- ==================== SCHEDULE BLOCKS ====================

CREATE TABLE IF NOT EXISTS public.schedule_blocks (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('learn', 'prep', 'apply', 'focus', 'other')),
  title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 200),
  starts_at TIMESTAMPTZ NOT NULL,
  ends_at TIMESTAMPTZ NOT NULL,
  google_event_id TEXT CHECK (google_event_id IS NULL OR char_length(google_event_id) <= 1024),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT schedule_blocks_time_order CHECK (ends_at > starts_at),
  CONSTRAINT schedule_blocks_max_length CHECK (ends_at - starts_at <= INTERVAL '24 hours')
);

CREATE INDEX IF NOT EXISTS idx_schedule_blocks_user_starts
  ON public.schedule_blocks(user_id, starts_at);

ALTER TABLE public.schedule_blocks ENABLE ROW LEVEL SECURITY;

